# \n for line change
str1 = " My name is Soban Amjad.\n I am a Full Stack Developer"
print(str1)
# /t for Tab Space
str2 = " My name is Soban Amjad.\t I am a Full Stack Developer"
print(str2)
# Concatenation Add 2 Strings
str3 = "Soban"
str4 = "Amjad"
final_str = str3 + " " + str4
print(final_str)

